// Joins every migration into supabase/schema.sql, for pasting into the Supabase SQL Editor.
// Every migration is written to be safe to re-run, so running the whole file is always fine.
//   node scripts/build-schema.mjs          (write)
//   node scripts/build-schema.mjs --check  (fail if schema.sql is out of date; used in CI)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = new URL("../supabase/migrations/", import.meta.url).pathname;
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const header = `-- tsayvish database: every migration in supabase/migrations, in order.
-- GENERATED by scripts/build-schema.mjs. Don't edit this file; add a new migration instead.
-- Paste the whole file into Supabase → SQL Editor → Run. It's safe to run again.
`;
const body = files.map((f) => `\n-- ▓▓▓▓▓▓▓▓ ${f} ▓▓▓▓▓▓▓▓\n\n${readFileSync(join(dir, f), "utf8").trim()}\n`).join("");
const out = header + body;
const target = new URL("../supabase/schema.sql", import.meta.url).pathname;

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== out) {
    console.error("supabase/schema.sql is out of date. Run: npm run db:schema");
    process.exit(1);
  }
  console.log(`schema.sql is up to date (${files.length} migrations)`);
} else {
  writeFileSync(target, out);
  console.log(`Wrote supabase/schema.sql from ${files.length} migrations`);
}
